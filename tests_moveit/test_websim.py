def test_browser_server_has_only_fixed_readonly_resources(tmp_path):
    assets = tmp_path / "assets"
    assets.mkdir()
    for name in ("three.module.js", "three.core.js", "OrbitControls.js"):
        (assets / name).write_text("// test fixture", encoding="utf-8")
    page = tmp_path / "page.html"
    page.write_text("<p>PICO</p>", encoding="utf-8")
    view = BrowserView(page, assets, {"meshes": [], "geoms": []}, port=0)
    view.update({"controller": "official", "enabled": False})
    view.start()
    url = "http://127.0.0.1:" + str(view.server.server_port)
    try:
        assert json.load(urllib.request.urlopen(url + "/state"))["enabled"] is False
        with pytest.raises(urllib.error.HTTPError) as error:
            urllib.request.urlopen(urllib.request.Request(url + "/control", data=b'{}'))
        assert error.value.code == 501
        with pytest.raises(urllib.error.HTTPError) as error:
            urllib.request.urlopen(url + "/static/../../secret")
        assert error.value.code == 404
    finally:
        view.close()


def test_browser_launch_cannot_load_a_robot_driver_or_autogenerated_input():
    source = (ROOT / "ros2_ws/src/rm65_servo_teleop/launch/pico_web.launch.py").read_text(encoding="utf-8")
    assert 'executable="rm_driver"' not in source and 'executable="rm65_driver_bridge"' not in source
    assert 'executable="xr_sdk_node"' in source
    assert '"allow_synthetic": test_only' in source
    assert 'RM65_WEBSIM_TEST_ONLY' in source

def test_jtc_cannot_activate_with_unpopulated_zero_state():
    names = [f"joint{i}" for i in range(1, 7)]
    home = [0, 0, -1.0472, 0, 1.0472, 0]
    assert not matches_initial_feedback(names, [0] * 6, home)
    assert matches_initial_feedback(names[::-1], home[::-1], home)
    assert not matches_initial_feedback(names, [float("nan")] * 6, home)


@pytest.mark.parametrize("controller", ["official", "servo"])
def test_browser_preview_never_queries_network_or_starts_process(monkeypatch, controller):
    def forbidden(*args, **kwargs):
        pytest.fail("browser preview caused an external action")
    monkeypatch.setattr(launcher, "get_pico_candidates", forbidden)
    monkeypatch.setattr(launcher, "run_command", forbidden)
    monkeypatch.setattr(launcher, "setup_pico_network", forbidden)
    assert launcher.main("pico", ["--browser", "--controller", controller, "--check-only"]) == 0
    plan = websim.commands(controller, "fixture-source-sha")
    assert "RM65_WITH_XR_SDK=ON" in plan[0]
    assert "controller:=" + controller in plan[-1]
    assert "input_source:=pico" in plan[-1]
    assert "rm_driver" not in json.dumps(plan)
    command = desktop.simulation_command("pico", distro="RM65-Servo", browser=True, controller=controller, preview=True)
    assert command[-4:] == ["--browser", "--controller", controller, "--check-only"]


